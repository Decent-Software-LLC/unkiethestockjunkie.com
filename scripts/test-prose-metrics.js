#!/usr/bin/env node
/**
 * Tests for scripts/lib/prose-metrics.js -- the single definition of "is this long enough to publish".
 *
 * Length decides two expensive things: whether the generator spends another completion plus an illustration on a
 * draft, and whether the gate lets the finished page onto a minors-facing site. It used to be measured three
 * different ways, which produced two separate failures and one false alarm:
 *
 *   - the retry loop counted heading and table words as prose, so short drafts cleared the retry check, cost an
 *     image request, then died at the gate;
 *   - the progress tables counted 5+ letter words only, publishing numbers ~45% below what the gate measured --
 *     bad enough that a complete, healthy corpus was diagnosed as containing 33 thin pages and a rewrite program
 *     was nearly scheduled against nothing.
 *
 * So these tests assert agreement between the consumers rather than trusting any one of them to look right.
 */

'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const { countProseWords, stripNonProse } = require('./lib/prose-metrics');
const { checkCandidate, MIN_WORDS } = require('./lib/candidate-gate');
const { proseWords } = require('./lib/content-inventory');
const gen = require('./generate-article');

let passed = 0, failed = 0;
function test(name, fn) {
  try { fn(); passed++; console.log(`  \u2713 ${name}`); }
  catch (e) { failed++; console.error(`  \u2717 ${name}\n      ${String(e.message).split('\n').slice(0, 6).join('\n      ')}`); }
}

const ROOT = path.join(__dirname, '..');

// A fixture built so the three retired definitions disagreed loudly: most "words" live in headings and a
// comparison table, with just enough body prose to sit near the floor either way.
const TABLE_PAGE = [
  '## What The Ratio Actually Measures',
  '',
  'The ratio compares cash generated by operations against profit reported after accounting choices were made.',
  'When those two lines drift apart across several years, someone should be able to explain why in plain terms,',
  'and the explanation should survive being read out loud to somebody paid to disagree with you about money.',
  '',
  '| Measure | Reported | Cash | Read |',
  '|---|---|---|---|',
  '| Revenue | high | steady | growth without collection proves nothing yet |',
  '| Profit | improving | flat | accrual choices smoothing recognition of doubtful receivables daily |',
  '',
  '## Why Beginners Should Check This Before Anything Else',
  '',
  'Because companies can survive losing money for years but cannot survive running out of cash while creditors',
  'hold dates they expect honoured, and nobody outside the building knows which situation they are describing.',
].join('\n');

test('the reporter, the gate and the generator agree on one number', () => {
  const inventoryNumber = proseWords(TABLE_PAGE);
  const generatorNumber = gen.countProseWords(TABLE_PAGE);
  // Gate measurement goes through checkCandidate's own path; compare against the shared function directly.
  const canonical = countProseWords(TABLE_PAGE);
  assert.strictEqual(inventoryNumber, canonical, 'inventory disagrees with the canonical metric');
  assert.strictEqual(generatorNumber, canonical, 'generator disagrees with the canonical metric');
});

test('headings and table rows do not count toward length', () => {
  const withChrome = countProseWords(TABLE_PAGE);
  const bodyOnly = countProseWords(TABLE_PAGE
    .replace(/^#{1,6}.*$/gm, '')
    .replace(/^\s*\|.*\|$/gm, ''));
  assert.strictEqual(withChrome, bodyOnly, 'structural text leaked into the prose count');
  assert.ok(countProseWords('| a | b | c |\n| 1 | 2 | 3 |') === 0, 'a pure table must measure zero prose');
});

test('fenced code does not inflate a draft', () => {
  const code = ['```js', 'const portfolioAllocation = calculateRebalancingThreshold(everySingleHolding);',
    'function estimateWithdrawalSustainability(baselineBalance, inflationAssumption) { return baselineBalance; }', '```'].join('\n');
  assert.ok(countProseWords(code) < 12, `code counted as prose (${countProseWords(code)})`);
});

test('sub-threshold drafts are measured low enough that the retry loop cannot hide them', () => {
  // Regression: the old generator count included headings and tables, so a draft like this looked publishable
  // to the retry loop and then failed at the gate -- after the illustration had already been requested.
  const thin = [
    '## Heading One Words That Do Not Count Here At All',
    '| Column | Value | Interpretation Meaningfully Long Cell Text |',
    '|---|---|---|',
    '| Alpha | Ten | Describes something in considerable verbosity inside a table cell |',
    'Body sentence about cash flow and profit drifting apart over many quarters in ways auditors must describe.',
  ].join('\n');
  assert.ok(countProseWords(thin) < MIN_WORDS, 'fixture should sit under the floor under the canonical metric');
  assert.ok(gen.countProseWords(thin) < MIN_WORDS, 'retry loop would still accept an unpublishable draft');
});

test('every published page clears the gate floor under the shared metric', () => {
  // This is the honest form of the claim that previously came out wrong: measured with the broken counter,
  // 33 healthy articles appeared to sit under 450 words. Under the shared metric none may sit under the floor.
  const dir = path.join(ROOT, '_articles');
  const rows = fs.readdirSync(dir).filter((f) => f.endsWith('.md'));
  const offenders = [];
  let min = Infinity, total = 0;
  for (const f of rows) {
    const src = fs.readFileSync(path.join(dir, f), 'utf8');
    const body = src.replace(/^---[\s\S]*?---\s*/, '');
    const w = proseWords(body);
    min = Math.min(min, w); total += w;
    if (w < MIN_WORDS) offenders.push(`${f} (${w})`);
  }
  assert.deepStrictEqual(offenders, [], `pages below the publication floor: ${offenders.join(', ')}`);
  assert.ok(min >= MIN_WORDS && rows.length > 100);
  console.log(`      (corpus: ${rows.length} pages, min ${min}, mean ${Math.round(total / rows.length)})`);
});

test('no module re-implements the significant-word rule', () => {
  const offenders = [];
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { scan(p); continue; }
      if (!e.name.endsWith('.js')) continue;
      if (/lib\/prose-metrics\.js$/.test(p.replace(ROOT + path.sep, ''))) continue;
      const src = fs.readFileSync(p, 'utf8');
      if (/\[[A-Za-z]\]\{[3-9],\}/.test(src)) offenders.push(path.relative(ROOT, p));
    }
  };
  scan(path.join(ROOT, 'scripts'));
  assert.deepStrictEqual(offenders, [], 'word-length rules belong in lib/prose-metrics.js only');
});

console.log(`\n${passed} passed, ${failed} failed\n`);
process.exit(failed ? 1 : 0);
