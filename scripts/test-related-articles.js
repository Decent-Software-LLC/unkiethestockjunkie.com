#!/usr/bin/env node
/**
 * Regression tests for scripts/lib/related-articles.js and the backfill script.
 *
 * Run: npm test
 *
 * These encode bugs actually hit while building related-article linking; each one
 * failed silently (wrong data, never an exception), so they are worth pinning:
 *   1. ARTICLES_DIR resolved relative to scripts/ instead of the repo root
 *   2. nested `    description:` read as a top-level key, corrupting descriptions
 *   3. closing front-matter fence not found when no newline follows it
 *   4. re-running the backfill mutating files instead of leaving them alone
 *   5. "$" in replacement strings being interpreted by String.replace
 */

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const {
  parseFrontMatter,
  splitFrontMatter,
  loadArticleIndex,
  rankRelated,
  toFrontMatter,
  urlFromFile
} = require('./lib/related-articles');

let passed = 0;
let failed = 0;

function test(name, fn) {
  try {
    fn();
    passed++;
    console.log(`  ✓ ${name}`);
  } catch (err) {
    failed++;
    console.error(`  ✗ ${name}\n      ${err.message}`);
  }
}

/** Build a corpus file with control over title/difficulty/tags/description. */
function makeArticle({ title, difficulty = 'beginner', tags = [], description = 'desc', body }) {
  return [
    '---',
    'layout: article',
    `title: "${title}"`,
    `description: "${description}"`,
    'date: 2026-01-01',
    `difficulty: ${difficulty}`,
    `tags: [${tags.map((t) => `"${t}"`).join(', ')}]`,
    'image: "/assets/images/articles/x.jpg"',
    'image_credit: "Generated by NVIDIA FLUX"',
    'image_credit_url: "https://build.nvidia.com/flux_1-schnell"',
    '---',
    '',
    body ?? 'Body paragraph.',
    ''
  ].join('\n');
}

console.log('\nrelated-articles\n');

// --- parsing ---------------------------------------------------------------

test('parseFrontMatter reads column-0 keys only', () => {
  const fm = parseFrontMatter(makeArticle({ title: 'T', description: 'REAL' }));
  assert.strictEqual(fm.title, 'T');
  assert.strictEqual(fm.description, 'REAL');
});

test('nested indented keys do NOT overwrite top-level ones (bug 2)', () => {
  // A related_articles block adds its own `    description:` lines. If those were
  // parsed as top-level, the last one would clobber the real description and the
  // corruption would spread through every later recommendation.
  const raw =
    makeArticle({ title: 'T', description: 'REAL' }).replace(
      '\n---\n',
      '\nrelated_articles:\n  - title: "Other"\n    url: "/articles/other/"\n' +
        '    description: "WRONG VALUE LEAKED FROM NESTED ITEM"\n---\n'
    );
  const fm = parseFrontMatter(raw);
  assert.strictEqual(fm.description, 'REAL', 'top-level description must win');
});

test('tags array is parsed', () => {
  const fm = parseFrontMatter(makeArticle({ title: 'T', tags: ['a', 'b', 'beginner'] }));
  assert.deepStrictEqual(fm.tags, ['a', 'b', 'beginner']);
});

test('urlFromFile strips leading date and .md', () => {
  assert.strictEqual(
    urlFromFile('2026-03-24-roe-return-on-equity-explained.md'),
    '/articles/roe-return-on-equity-explained/'
  );
});

// --- splitting -------------------------------------------------------------

test('splitFrontMatter round-trips losslessly', () => {
  const raw = makeArticle({ title: 'T', description: 'D' });
  const p = splitFrontMatter(raw);
  assert.ok(p);
  assert.strictEqual(`${p.leading}${p.frontMatter}${p.trailing}`, raw);
});

test('splitFrontMatter finds fence when body has many "---" rules (real corpus shape)', () => {
  // Several corpus files contain dozens of bare "---" setext underlines in the body.
  const raw = makeArticle({
    title: 'T',
    description: 'D',
    body: 'Intro.\n\n---\n\nSection A\n\n---\n\nSection B\n'
  });
  const p = splitFrontMatter(raw);
  assert.ok(p);
  assert.ok(!p.frontMatter.includes('Section A'), 'body must stay out of front matter');
  assert.ok(p.trailing.includes('Section A'));
});

test('splitFrontMatter handles glued "---### Heading" fence (bug 3)', () => {
  // Pre-existing articles contain this; previously returned null and got skipped.
  const raw = makeArticle({ title: 'T', description: 'D' }).replace('\n---\n', '\n---### Difficulty: Beginner\n');
  const p = splitFrontMatter(raw);
  assert.ok(p, 'must still recognise the front matter');
  assert.ok(p.trailing.startsWith('\n---### Difficulty:'), 'glued heading preserved verbatim');
});

test('backfill repairs glued fence so Jekyll can read the key', () => {
  // The block is useless if Jekyll cannot parse it: one corpus article stayed
  // link-less until the fused fence was repaired.
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'unkie-fence-'));
  const dir = path.join(tmp, '_articles');
  const scripts = path.join(tmp, 'scripts');
  fs.mkdirSync(dir, { recursive: true });
  fs.mkdirSync(scripts, { recursive: true });
  fs.cpSync(path.join(__dirname, 'lib'), path.join(scripts, 'lib'), { recursive: true });
  fs.copyFileSync(
    path.join(__dirname, 'backfill-related-articles.js'),
    path.join(scripts, 'backfill-related-articles.js')
  );

  // Realistic glued-fence shape: the leaked heading follows the closing fence with no
  // separating newline, and body text runs straight on (as in the corpus file). Built
  // directly rather than by string-replacing makeArticle(), whose blank line before
  // the fence makes a naive replace swallow the newline the repair regex is anchored on.
  // Needs >=3 mutually-related articles: each article's recommendation list must clear
  // MIN_RELATED_SCORE for at least two others, otherwise the "don't link weak matches"
  // guardrail skips the file and the fence repair never runs. A 2-article corpus looks
  // like a repair failure but is the guardrail behaving correctly.
  const mk = (t, tags) =>
    [
      '---',
      'layout: article',
      `title: "${t}"`,
      `description: "${t} d"`,
      'date: 2026-01-01',
      'difficulty: beginner',
      `tags: [${tags.map((x) => JSON.stringify(x)).join(', ')}]`,
      'image: "/assets/images/articles/x.jpg"',
      '---### Difficulty: Beginner',
      `### Tags: ${tags.join(', ')}`,
      'Body paragraph.',
      ''
    ].join('\n');

  const shared = ['stocks', 'basics'];
  fs.writeFileSync(path.join(dir, '2026-01-01-a.md'), mk('Alpha', shared));
  fs.writeFileSync(path.join(dir, '2026-01-02-b.md'), mk('Beta', shared));
  fs.writeFileSync(path.join(dir, '2026-01-03-c.md'), mk('Gamma', shared));

  execFileSync(process.execPath, [path.join(scripts, 'backfill-related-articles.js')], {
    cwd: tmp,
    encoding: 'utf8'
  });

  const out = fs.readFileSync(path.join(dir, '2026-01-01-a.md'), 'utf8');
  assert.ok(!out.includes('---###'), 'glued fence must be repaired');
  assert.ok(!/^### Difficulty:/m.test(out), 'leaked difficulty heading removed');
  assert.ok(!/^### Tags:/m.test(out), 'leaked tags heading removed');
  assert.match(out, /^related_articles:/m, 'links attached');

  // Body content after the repair must survive.
  assert.ok(out.includes('Body paragraph.'), 'body preserved through repair');

  // Still idempotent after repairing.
  const before = out;
  execFileSync(process.execPath, [path.join(scripts, 'backfill-related-articles.js')], {
    cwd: tmp,
    encoding: 'utf8'
  });
  assert.strictEqual(fs.readFileSync(path.join(dir, '2026-01-01-a.md'), 'utf8'), before);

  fs.rmSync(tmp, { recursive: true, force: true });
});

test('splitFrontMatter returns null without front matter', () => {
  assert.strictEqual(splitFrontMatter('just some body text'), null);
});

// --- ranking ---------------------------------------------------------------

function corpusOf(specs) {
  return specs.map((s) => ({
    file: s.file,
    title: s.title,
    description: s.description ?? `${s.title} desc`,
    difficulty: s.difficulty,
    tags: s.tags,
    url: `/articles/${s.file.replace(/^\d{4}-\d{2}-\d{2}-/, '').replace(/\.md$/, '')}/`
  }));
}

test('never recommends an article to itself', () => {
  const c = corpusOf([
    { file: '2026-01-01-a.md', title: 'A', difficulty: 'beginner', tags: ['x'] },
    { file: '2026-01-02-b.md', title: 'B', difficulty: 'beginner', tags: ['x'] }
  ]);
  const r = rankRelated(c[0], c);
  assert.ok(r.every((r) => r.url === c[1].url));
});

test('tag overlap outranks difficulty-only match', () => {
  const c = corpusOf([
    { file: '2026-01-01-host.md', title: 'HOST', difficulty: 'beginner', tags: ['stocks', 'basics'] },
    { file: '2026-01-02-strong.md', title: 'STRONG', difficulty: 'advanced', tags: ['stocks'] },
    { file: '2026-01-03-weak.md', title: 'WEAK', difficulty: 'beginner', tags: ['psychology'] }
  ]);
  const r = rankRelated(c[0], c);
  assert.strictEqual(r[0].title, 'STRONG', '1 shared tag (score 2) beats same difficulty (score 1)');
});

test('drops candidates that share no tags (guardrail)', () => {
  const c = corpusOf([
    { file: '2026-01-01-host.md', title: 'HOST', difficulty: 'beginner', tags: ['stocks'] },
    { file: '2026-01-02-unrelated.md', title: 'UNRELATED', difficulty: 'intermediate', tags: ['crypto'] }
  ]);
  assert.strictEqual(rankRelated(c[0], c).length, 0);
});

test('caps recommendations at 3', () => {
  const c = corpusOf([
    { file: '2026-01-01-host.md', title: 'HOST', difficulty: 'beginner', tags: ['t'] },
    ...Array.from({ length: 8 }, (_, i) => ({
      file: `2026-01-${String(i + 2).padStart(2, '0')}-x${i}.md`,
      title: `X${i}`,
      difficulty: 'beginner',
      tags: ['t']
    }))
  ]);
  assert.strictEqual(rankRelated(c[0], c).length, 3);
});

test('ranking is deterministic despite score ties', () => {
  // Eight equally-scoring candidates for three slots: tie order decides output,
  // so it must be pinned (score desc, then filename asc).
  const c = corpusOf([
    { file: '2026-01-01-host.md', title: 'HOST', difficulty: 'beginner', tags: ['t'] },
    ...Array.from({ length: 8 }, (_, i) => ({
      file: `2026-01-${String(i + 2).padStart(2, '0')}-x${i}.md`,
      title: `X${i}`,
      difficulty: 'beginner',
      tags: ['t']
    }))
  ]);
  const first = rankRelated(c[0], c);
  for (let i = 0; i < 25; i++) {
    assert.deepStrictEqual(rankRelated(c[0], c), first, `run ${i} diverged`);
  }
});

// --- rendering -------------------------------------------------------------

test('toFrontMatter omits blocks with fewer than 2 items', () => {
  assert.strictEqual(toFrontMatter([]), '');
  assert.strictEqual(toFrontMatter([{ title: 'A', url: '/a/', description: 'd' }]), '');
});

test('toFrontMatter renders valid list entries', () => {
  const out = toFrontMatter([
    { title: 'A', url: '/a/', description: 'd1' },
    { title: 'B', url: '/b/', description: 'd2' }
  ]);
  assert.ok(out.startsWith('related_articles:\n'));
  assert.ok(out.includes('  - title: "A"'));
  assert.ok(out.includes('    url: "/a/"'));
  assert.ok(out.includes('    description: "d1"'));
});

test('toFrontMatter escapes quotes instead of breaking YAML', () => {
  const out = toFrontMatter([
    { title: 'The "Best" Guide', url: '/a/', description: 'it\'s fine' },
    { title: 'B', url: '/b/', description: 'd2' }
  ]);
  assert.ok(out.includes('\\"Best\\"'));
});

test('dollar signs survive rendering (bug 5: String.replace $ handling)', () => {
  const dollars = '$&$\'$`$$';
  const out = toFrontMatter([
    { title: `Turn ${dollars}100 into millions`, url: '/a/', description: `worth ${dollars}1000` },
    { title: 'B', url: '/b/', description: 'd2' }
  ]);
  assert.ok(out.includes(dollars), 'literal $ sequences must pass through unmodified');
});

// --- corpus + end-to-end backfill ----------------------------------------

test('ARTICLES_DIR resolves to the repo corpus (bug 1)', () => {
  const corpus = loadArticleIndex();
  assert.ok(corpus.length > 50, `expected the real corpus, loaded ${corpus.length}`);
  assert.ok(corpus.every((a) => a.title && a.url.startsWith('/articles/')));
});

test('every corpus article gets at least 2 recommendations', () => {
  const corpus = loadArticleIndex();
  const weak = corpus.filter((a) => rankRelated(a, corpus).length < 2);
  assert.strictEqual(weak.length, 0, `under-linked: ${weak.map((w) => w.file).join(', ')}`);
});

test('backfill is idempotent on a scratch copy (bug 4)', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'unkie-rel-'));
  const articlesDir = path.join(tmp, '_articles');
  const scriptsDir = path.join(tmp, 'scripts');
  fs.mkdirSync(articlesDir, { recursive: true });
  fs.mkdirSync(scriptsDir, { recursive: true });

  fs.cpSync(path.join(__dirname, 'lib'), path.join(scriptsDir, 'lib'), { recursive: true });
  fs.copyFileSync(
    path.join(__dirname, 'backfill-related-articles.js'),
    path.join(scriptsDir, 'backfill-related-articles.js')
  );

  // A representative slice incl. the awkward shapes: glued fence, setext rules, $.
  const samples = [
    makeArticle({ title: 'Alpha', description: 'Invest $1,000 wisely', tags: ['stocks', 'basics'], difficulty: 'beginner' }),
    makeArticle({ title: 'Beta', description: 'Use $ & $ special chars', tags: ['stocks', 'basics'], difficulty: 'beginner' }),
    makeArticle({ title: 'Gamma', description: 'Rules', tags: ['stocks'], difficulty: 'intermediate', body: 'A\n\n---\n\nB\n\n===\n\nC\n' }),
    makeArticle({ title: 'Delta', description: 'Glued', tags: ['stocks', 'basics'], difficulty: 'beginner' }).replace('\n---\n', '\n---### Difficulty: Beginner\n')
  ];
  samples.forEach((content, i) => {
    fs.writeFileSync(path.join(articlesDir, `2026-01-0${i + 1}-${['alpha', 'beta', 'gamma', 'delta'][i]}.md`), content);
  });

  const run = () =>
    execFileSync(process.execPath, [path.join(scriptsDir, 'backfill-related-articles.js')], {
      cwd: tmp,
      encoding: 'utf8'
    });

  run();
  const afterFirst = Object.fromEntries(
    fs.readdirSync(articlesDir).map((f) => [f, fs.readFileSync(path.join(articlesDir, f), 'utf8')])
  );

  run();
  run();

  for (const [file, before] of Object.entries(afterFirst)) {
    const now = fs.readFileSync(path.join(articlesDir, file), 'utf8');
    assert.strictEqual(now, before, `${file} changed on re-run (not idempotent)`);
  }

  // Front matter got links; bodies were left untouched.
  for (const file of fs.readdirSync(articlesDir)) {
    const now = fs.readFileSync(path.join(articlesDir, file), 'utf8');
    assert.match(now, /^related_articles:/m, `${file} missing links`);
    const p = splitFrontMatter(now);
    assert.ok(p, `${file} lost its parseable front matter`);
    assert.ok(p.trailing.length > 0, `${file} lost its body`);
  }

  // Literal dollars preserved from source through to rendered output.
  const alpha = fs.readFileSync(path.join(articlesDir, '2026-01-01-alpha.md'), 'utf8');
  assert.ok(alpha.includes('$1,000'), 'dollar amounts must not be mangled');

  fs.rmSync(tmp, { recursive: true, force: true });
});

console.log(`\n${passed} passed, ${failed} failed\n`);
process.exit(failed ? 1 : 0);
